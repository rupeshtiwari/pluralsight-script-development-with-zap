#!/usr/bin/env python3
"""Auditable, course-specific handoff for a SEPARATE narration-authoring skill.

No proof generation, text invention or automatic CQA approval occurs here.
"""
from __future__ import annotations
import json
from pathlib import Path
from typing import Any

SCHEMA_VERSION = 1
PAUSE_V2 = '<break time="1.0s" />'
PAUSE_V4 = '[pause]'


def spoken_words(value: str) -> int:
    return len(value.split())


def validate_final(candidate: Any, demo: str, sha: str, commands: list[str]) -> tuple[dict | None, list[str]]:
    """Validate imported narration structure and exact demo contract, never provenance by assertion."""
    errors: list[str] = []
    if not isinstance(candidate, dict):
        return None, ["final narration is not a JSON object"]
    if candidate.get('schema_version') != SCHEMA_VERSION:
        errors.append('schema_version must be 1')
    if candidate.get('demo') != demo:
        errors.append('demo ID does not match this evidence package')
    if candidate.get('reference_sha') != sha or not sha:
        errors.append('reference_sha differs from the Developer preflight')
    steps = candidate.get('steps')
    if not isinstance(steps, list) or len(steps) != 4:
        errors.append('exactly four narration steps are required')
    else:
        for i, item in enumerate(steps, 1):
            if not isinstance(item, dict) or item.get('step') != i:
                errors.append(f'step {i} has an invalid index')
                continue
            if len(commands) != 4 or item.get('command') != commands[i-1]:
                errors.append(f'step {i} command mismatch')
            for stage in ('before', 'during', 'after'):
                value = item.get(stage)
                if not isinstance(value, str) or not value.strip():
                    errors.append(f'step {i} {stage} speech missing')
                elif spoken_words(value) > 27:
                    errors.append(f'step {i} {stage} exceeds 27 spoken whitespace tokens')
                elif '<break' in value or '[pause]' in value:
                    errors.append(f'step {i} {stage} embeds pause tags; pauses are generated by model mode')
    checks = candidate.get('quality_checks', {})
    if not isinstance(checks, dict):
        errors.append('quality_checks must be a dictionary')
    if errors:
        return None, errors
    return candidate, []


def evidence_ready(final: dict) -> bool:
    """Only classifies a DECLARED sign-off; supporting files must be inspected by CQA."""
    checks = final.get('quality_checks') or {}
    return bool(checks.get('same_take_verified') is True and
                checks.get('gui_ci_evidence_verified') is True and
                checks.get('cqa_approved') is True and
                isinstance(checks.get('approved_by'), str) and checks['approved_by'].strip() and
                isinstance(final.get('take_id'), str) and final['take_id'].strip())


def tts_text(final: dict, mode: str = 'v2') -> str:
    """Pure words + documented compatible nonspoken pause tags; never stage headings."""
    tag = PAUSE_V2 if mode == 'v2' else PAUSE_V4 if mode == 'v4' else None
    if tag is None:
        raise ValueError('model must be v2 or v4')
    lines = []
    opening = final.get('opening')
    if isinstance(opening, str) and opening.strip():
        lines.append(opening.strip())
        lines.append(tag)
    for step in final['steps']:
        lines.extend((step['before'].strip(), tag, step['during'].strip(), tag, step['after'].strip(), tag))
    closing = final.get('closing')
    if isinstance(closing, str) and closing.strip():
        lines.append(closing.strip())
    elif lines:
        lines.pop()  # no needless trailing audio tag
    return '\n'.join(lines).strip()+'\n'


def write_narration_handoff(output: Path, data: dict) -> Path:
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    target = output / 'narration-handoff.json'
    target.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    readme = [f'# {data["demo"]} — Evidence-Locked Narration Handoff','',
    '**DRAFT INPUT — NOT approved narration.** Use the real preflight and separately recorded GUI/CI evidence.','',
    '## Fixed source and LO','',f'- Reference branch: `{data["reference_branch"]}`',
    f'- SHA: `{data["reference_sha"] or "NOT VERIFIED"}`',
    f'- Learning objectives: {data["learning_objectives"]}',
    f'- Production status: **{data["status"]}**','',
    '## Procedure for the separate narration skill','',
    '1. Load this JSON, the step terminal and raw proof files, and actual Recorder footage / GUI or hosted CI proof. Reject any missing or stale evidence.','2. Apply the Rupesh teaching-style and teaching-narration skill references from the distributed production skill. Preserve approved command order and all visible mechanisms.','3. Produce THREE human, ElevenLabs-safe spoken beats per step: BEFORE command, DURING current result, AFTER operator decision, each at most 27 spoken words; word-count in Python.','4. Write narration-final.json with the documented schema and narration-final.md containing step-by-step exact speech, visual trigger, word count and proof reference.','5. Set quality_checks fields to false until same-take GUI/CI proof is captured, reconciled and independently signed off. Never assert CQA approval from terminal PASS alone.','6. Place the outputs in the SAME demo folder and run `./refresh.sh` from the batch root, then refresh index.html in the local browser.','',
    '## Model-specific pauses','',
    '- Eleven Multilingual v2 / Flash v2 / v2.5: exact one-second `<break time="1.0s" />` at the approved audio transitions','- Eleven v3/v4: `[pause]` audio tags are approximate; the Editor inserts a measured one-second gap as needed','- Spoken lines must **not** contain tags or stage directions. The portal inserts compatible pause syntax on export.','',
    '## Four frozen commands','']
    for step in data['steps']:
        readme += [f'### Step {step["step"]}: {step["title"]}', '',
                   f'**Run from:** `{step["working_directory"]}`',
                   f'**Exact script:** `{step["command"]}`',
                   f'**Proof status:** {"REAL terminal data captured" if step["proof_verified"] else "HOLD: missing or failing evidence"}',
                   '**Recorder’s reference narration (NOT FINAL):**', '']
        for name, speech, count in step['draft_beats']:
            readme += [f'- {name}: {speech} ({count} words)']
        readme += ['',f'**Raw audit:** `{step["raw_log"]}`',f'**Terminal:** `{step["terminal_log"]}`','']
    (output/'NARRATION_HANDOFF.md').write_text('\n'.join(readme)+'\n',encoding='utf-8')
    template = {'schema_version': 1, 'demo': data['demo'], 'reference_sha': data['reference_sha'],
                'take_id':'', 'opening':'', 'closing':'',
                'quality_checks':{'same_take_verified':False,'gui_ci_evidence_verified':False,
                'cqa_approved':False,'approved_by':''},
                'evidence_refs':{'terminal':['logs/preflight-step-01.log','logs/preflight-step-02.log',
                'logs/preflight-step-03.log','logs/preflight-step-04.log'], 'gui_ci':[]},
                'steps':[{'step':x['step'],'command':x['command'],
                          'before': x['draft_beats'][0][1] if len(x['draft_beats'])>=1 else '',
                          'during': x['draft_beats'][1][1] if len(x['draft_beats'])>=2 else '',
                          'after': x['draft_beats'][2][1] if len(x['draft_beats'])>=3 else ''}
                         for x in data['steps']]}
    # A template contains the existing draft, not generated final content.
    (output/'narration-final.TEMPLATE.json').write_text(json.dumps(template,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return target
